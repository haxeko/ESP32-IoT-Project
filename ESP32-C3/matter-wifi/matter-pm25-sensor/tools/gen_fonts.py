#!/usr/bin/env python3
"""Generate the 1-bit bitmap fonts used by the OLED (main/ui/fonts.c).

Usage:
    pip install pillow
    python3 tools/gen_fonts.py Roboto-Regular.ttf Roboto-Bold.ttf > main/ui/fonts.c

The TTF files can be downloaded from Google Fonts (Roboto, weights 400 and 700).
"""
import sys

from PIL import ImageFont

ASCII = ''.join(chr(c) for c in range(0x20, 0x7F))
# Extra glyphs needed by the Vietnamese texts on the screen (air quality
# labels, "Đang đo...", factory reset screens).
VIETNAMESE = 'ĐđÁÉÔỐỰỲ' + 'ẠẶẾỊạặ'

# (C name, TTF index in argv, pixel size, characters)
FONTS = [
    ('font_small', 0, 12, ASCII + VIETNAMESE),
    ('font_medium', 1, 16, ASCII),
    ('font_large', 1, 28, ASCII),
]


def render_glyph(font, ch):
    mask, (x_off, y_off) = font.getmask2(ch, mode='1', anchor='ls')
    width, height = mask.size
    rows = []
    for y in range(height):
        row = bytearray((width + 7) // 8)
        for x in range(width):
            if mask.getpixel((x, y)):
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(bytes(row))
    advance = int(round(font.getlength(ch)))
    return width, height, x_off, y_off, advance, b''.join(rows)


def main():
    ttf_paths = sys.argv[1:3]
    if len(ttf_paths) != 2:
        sys.exit(__doc__)

    out = ['// Generated by tools/gen_fonts.py from Roboto (SIL Open Font License 1.1). Do not edit.',
           '', '#include "fonts.h"', '']
    for name, ttf_index, size, chars in FONTS:
        font = ImageFont.truetype(ttf_paths[ttf_index], size)
        ascent, descent = font.getmetrics()
        bitmap = bytearray()
        glyphs = []
        for ch in sorted(set(chars)):
            width, height, x_off, y_off, advance, data = render_glyph(font, ch)
            glyphs.append((ord(ch), len(bitmap), width, height, x_off, y_off, advance))
            bitmap += data

        out.append(f'static const uint8_t {name}_bitmap[] = {{')
        for i in range(0, len(bitmap), 16):
            out.append('    ' + ', '.join(f'0x{b:02x}' for b in bitmap[i:i + 16]) + ',')
        out.append('};')
        out.append('')
        out.append(f'static const font_glyph_t {name}_glyphs[] = {{')
        for cp, offset, width, height, x_off, y_off, advance in glyphs:
            out.append(f'    {{ 0x{cp:04x}, {offset}, {width}, {height}, {x_off}, {y_off}, {advance} }},')
        out.append('};')
        out.append('')
        out.append(f'const font_t {name} = {{')
        out.append(f'    .glyphs = {name}_glyphs,')
        out.append(f'    .glyph_count = {len(glyphs)},')
        out.append(f'    .bitmap = {name}_bitmap,')
        out.append(f'    .ascent = {ascent},')
        out.append(f'    .descent = {descent},')
        out.append('};')
        out.append('')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
